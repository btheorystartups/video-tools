def _forbidden_import_claims(text: str) -> list[str]:
    forbidden = ["is the same person", "face recognition", "voice identity", "diagnoses emotion", "will retain viewers", "automatically edit", "auto-resolve governance", "biometric"]
    lower = text.lower()
    return [item for item in forbidden if item in lower]


