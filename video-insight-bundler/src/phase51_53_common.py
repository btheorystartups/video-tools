def _e(value) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def _page(title: str, body: str, css_prefix: str = "../") -> str:
    return f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width, initial-scale=1'><title>{_e(title)}</title><link rel='stylesheet' href='{css_prefix}static_assets/report.css'></head><body><main class='main expert'><header class='page-header'><p>{_e(PHASE_NAME)}</p><h1>{_e(title)}</h1><p class='muted'>{_e(NON_CLAIM)}</p></header>{body}</main></body></html>"


def _cards(rows: list[dict], base: str = "", image_prefix: str = "../graphs/") -> str:
    body = "<section class='graph-card-grid'>"
    for row in rows:
        detail = row.get("detail_link") or row.get("detail_page_path") or "#"
        suffix = detail.replace("visualizations/graph_ux/", "")
        href = f"{base}{suffix}"
        image = row.get("graph_image_path") or ""
        image_href = image.replace("graphs/", image_prefix)
        image_html = f"<a class='graph-card-image-link' href='{_e(href)}'><img src='{_e(image_href)}' alt='{_e(row.get('graph_title'))} graph'></a>" if image else ""
        body += f"<article class='graph-card'>{image_html}<h3><a href='{_e(href)}'>{_e(row.get('graph_title'))}</a></h3><p><strong>{_e(row.get('status_badge') or row.get('review_priority') or 'review')}</strong></p><p>{_e(row.get('current_interpretation_line') or row.get('short_subtitle') or row.get('graph_family'))}</p><a class='more-link' href='{_e(href)}'>Open detail</a></article>"
    return body + "</section>"


