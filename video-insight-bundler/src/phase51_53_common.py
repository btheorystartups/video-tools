    out.update({"interpretation_packet_validation_id": deterministic_id("IPV", rows), "validation_entries": rows, "summary": {"validated_import_count": len(rows), "error_count": sum(1 for r in rows if r["validation_status"] != STATUS_COMPLETE)}})
    return out


