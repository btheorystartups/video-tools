def build_video_version_lineage(outputs: dict) -> dict:
    rows = _video_rows(outputs)
    candidates = []
    for left in rows:
        for right in rows:
            if left["video_id"] >= right["video_id"]:
                continue
            names = f"{left['title']} {right['title']}".lower()
            if any(token in names for token in ["v2", "version", "rev", "rough", "final", "revised"]):
                candidates.append({"candidate_pair": [left["video_id"], right["video_id"]], "lineage_status": "candidate_only", "confidence": "limited", "reason": "filename_or_metadata_version_hint"})
    out = _artifact("deterministic_video_version_lineage_v1", [SAME_SPEAKER_LIMITATION])
    out.update({"video_version_lineage_id": deterministic_id("VVL", candidates), "version_candidates": candidates, "summary": {"candidate_version_pair_count": len(candidates)}})
    return out


