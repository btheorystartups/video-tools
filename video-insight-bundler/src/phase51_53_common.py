def _metric_value(metric_id: str, outputs: dict) -> dict:
    for row in (outputs.get("graph_interpretation_index") or {}).get("graph_interpretations", []):
        if row.get("metric_id") == metric_id:
            return row.get("current_observed_values") or {"source": row.get("graph_path")}
    corpus = outputs.get("corpus_summary") or {}
    intelligence = outputs.get("corpus_intelligence") or {}
    diagnostics = outputs.get("governance_diagnostics") or {}
    if metric_id == "readiness_score":
        return {"value": corpus.get("corpus_readiness_score"), "source": "corpus/corpus_summary.json"}
    if metric_id in {"rhetorical_pressure", "speech_rate_wpm"}:
        return {"value": (intelligence.get("summary") or {}).get("mean_peak_pressure"), "source": "corpus/corpus_intelligence.json"}
    if metric_id == "governance_threshold_gap":
        return {"failed_threshold_count": (diagnostics.get("summary") or {}).get("failed_threshold_count", 0), "source": "governance/governance_diagnostics.json"}
    return {"qualitative": "review available when source artifact exists", "source": "dashboard/graph_interpretation_index.json"}


def _status(values: dict) -> str:
    value = values.get("value")
    if values.get("failed_threshold_count"):
        return "concern"
    if isinstance(value, (int, float)):
        return "concern" if value >= 0.75 else "caution" if value >= 0.45 else "good"
    return "review"


def build_observed_graph_value_interpretation(outputs: dict) -> dict:
    rows = []
    for entry in build_static_graph_meaning_catalog(outputs)["graph_meanings"]:
        values = _metric_value((entry.get("related_metric_families") or [""])[0], outputs)
        status = _status(values)
        if entry["graph_id"] == "pacing_curve":
            interpretation = "The pacing curve should be reviewed for high-WPM spikes and dense explanation regions. Spikes are candidate review points, not automatic defects."
        elif entry["graph_id"] == "emotional_arc":
            interpretation = "The emotional arc proxies should be read as tonal movement. Stable values may support a reflective style or may indicate low contrast depending on intent."
        elif entry["graph_id"] == "acoustic_energy":
            interpretation = "The acoustic energy proxy highlights candidate emphasis, silence, noise, or clipping checks. It is not a direct measure of emotion."
        elif entry["graph_id"] == "topic_timeline":
            interpretation = "The topic timeline should be reviewed for explicit bridges between deterministic term clusters and for repeated themes that support continuity."
        else:
            interpretation = f"{entry['graph_title']} has status {status}. Review linked evidence before making editorial or governance decisions."
        rows.append({
            "graph_id": entry["graph_id"],
            "current_observed_values": values,
            "value_summary": values.get("qualitative") or f"Observed deterministic value/status: {values}",
            "status_badge": status,
            "interpretation": interpretation,
            "review_priority": "high" if status == "concern" else "medium" if status == "caution" else "normal",
            "confidence": "medium" if values.get("source") else "limited",
            "optimization_summary": "Use low-risk review actions and preserve intentional style when evidence supports it.",
            "preserve_as_intentional_option": True,
            "human_review_recommended": status in {"concern", "caution", "review"},
            "evidence_refs": [values.get("source") or "dashboard/graph_interpretation_index.json"],
        })
    out = _artifact("deterministic_observed_graph_value_interpretation_v1")
    out.update({"observed_graph_value_interpretation_id": deterministic_id("OGVI", [(r["graph_id"], r["status_badge"]) for r in rows]), "graph_interpretations": rows, "summary": {"observed_graph_interpretation_count": len(rows)}})
    return out


