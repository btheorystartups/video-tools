    rows = []
    graph_ids = {g[0] for g in GRAPH_SPECS}
    for item in imported:
        text = json.dumps(item, ensure_ascii=False)
        missing = [key for key in ["graph_id", "author_type", "interpretation_text"] if not item.get(key)]
        forbidden = _forbidden_import_claims(text)
        rows.append({"packet_id": item.get("packet_id"), "graph_id": item.get("graph_id"), "validation_status": STATUS_COMPLETE if not missing and not forbidden and item.get("graph_id") in graph_ids else STATUS_ERROR, "missing_fields": missing, "forbidden_claims": forbidden})
